import { PryKryptError } from "./errors";

/**
 * PryKrypt container layout (embedded into the LSBs of the RGB channels):
 *
 *   offset  size  field
 *   0       8     magic  "PRYKRYPT"
 *   8       1     format version (currently 1)
 *   9       1     flags  (bit 0 = AES-GCM encrypted)
 *   10      4     body length (uint32, big endian)
 *   14      N     body
 *
 * Body, when NOT encrypted, is the serialized payload (see below).
 * Body, when encrypted, is: salt(16) | iv(12) | AES-GCM ciphertext(+16 tag).
 *
 * Serialized payload:
 *   byte 0 = 0  -> UTF-8 text (rest of body)
 *   byte 0 = 1  -> file: nameLen(2) | name | mimeLen(2) | mime | file bytes
 */

export const MAGIC = new Uint8Array([0x50, 0x52, 0x59, 0x4b, 0x52, 0x59, 0x50, 0x54]); // "PRYKRYPT"
export const FORMAT_VERSION = 1;
export const HEADER_LENGTH = 14;
export const FLAG_ENCRYPTED = 0x01;

export type PayloadType = "text" | "file";

export interface SecretPayload {
  type: PayloadType;
  text?: string;
  fileName?: string;
  mimeType?: string;
  fileBytes?: Uint8Array;
}

export interface ContainerHeader {
  version: number;
  encrypted: boolean;
  bodyLength: number;
}

const textEncoder = new TextEncoder();
const textDecoder = new TextDecoder();

export function serializePayload(payload: SecretPayload): Uint8Array {
  if (payload.type === "text") {
    const textBytes = textEncoder.encode(payload.text ?? "");
    const out = new Uint8Array(1 + textBytes.length);
    out[0] = 0;
    out.set(textBytes, 1);
    return out;
  }

  const nameBytes = textEncoder.encode(payload.fileName || "secret.bin");
  const mimeBytes = textEncoder.encode(payload.mimeType || "application/octet-stream");
  const data = payload.fileBytes ?? new Uint8Array(0);

  if (nameBytes.length > 0xffff || mimeBytes.length > 0xffff) {
    throw new PryKryptError("PAYLOAD_TOO_LARGE", "The file name or MIME type is too long.");
  }

  const out = new Uint8Array(1 + 2 + nameBytes.length + 2 + mimeBytes.length + data.length);
  let offset = 0;

  out[offset] = 1;
  offset += 1;

  out[offset] = (nameBytes.length >> 8) & 0xff;
  out[offset + 1] = nameBytes.length & 0xff;
  offset += 2;
  out.set(nameBytes, offset);
  offset += nameBytes.length;

  out[offset] = (mimeBytes.length >> 8) & 0xff;
  out[offset + 1] = mimeBytes.length & 0xff;
  offset += 2;
  out.set(mimeBytes, offset);
  offset += mimeBytes.length;

  out.set(data, offset);
  return out;
}

export function deserializePayload(bytes: Uint8Array): SecretPayload {
  if (bytes.length < 1) {
    throw new PryKryptError("CORRUPT_PAYLOAD", "The hidden payload is empty or corrupted.");
  }

  const type = bytes[0];

  if (type === 0) {
    return { type: "text", text: textDecoder.decode(bytes.subarray(1)) };
  }

  if (type === 1) {
    let offset = 1;

    const ensure = (count: number) => {
      if (offset + count > bytes.length) {
        throw new PryKryptError("CORRUPT_PAYLOAD", "The hidden file payload is truncated.");
      }
    };

    ensure(2);
    const nameLength = (bytes[offset] << 8) | bytes[offset + 1];
    offset += 2;
    ensure(nameLength);
    const fileName = textDecoder.decode(bytes.subarray(offset, offset + nameLength));
    offset += nameLength;

    ensure(2);
    const mimeLength = (bytes[offset] << 8) | bytes[offset + 1];
    offset += 2;
    ensure(mimeLength);
    const mimeType = textDecoder.decode(bytes.subarray(offset, offset + mimeLength));
    offset += mimeLength;

    return {
      type: "file",
      fileName: fileName || "secret.bin",
      mimeType: mimeType || "application/octet-stream",
      fileBytes: bytes.slice(offset),
    };
  }

  throw new PryKryptError("CORRUPT_PAYLOAD", "Unknown payload type inside the image.");
}

export function buildContainer(body: Uint8Array, encrypted: boolean): Uint8Array {
  const out = new Uint8Array(HEADER_LENGTH + body.length);
  out.set(MAGIC, 0);
  out[8] = FORMAT_VERSION;
  out[9] = encrypted ? FLAG_ENCRYPTED : 0;
  out[10] = (body.length >>> 24) & 0xff;
  out[11] = (body.length >>> 16) & 0xff;
  out[12] = (body.length >>> 8) & 0xff;
  out[13] = body.length & 0xff;
  out.set(body, HEADER_LENGTH);
  return out;
}

