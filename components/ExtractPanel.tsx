"use client";

import { useCallback, useEffect, useState } from "react";
import { Copy, Download, FileText, KeyRound, Lock, RefreshCw, Unlock, X } from "lucide-react";

import Alert from "@/components/Alert";
import ImageDropzone from "@/components/ImageDropzone";
import Reveal from "@/components/Reveal";
import StepHeader from "@/components/StepHeader";
import { deserializePayload, type SecretPayload } from "@/lib/container";
import { decryptBytes } from "@/lib/crypto";
import { PryKryptError, toMessage } from "@/lib/errors";
import { formatBytes } from "@/lib/format";
import { readImageData } from "@/lib/image";
import { extractContainer } from "@/lib/stego";

type Stage = "idle" | "reading" | "locked" | "done" | "error";

type ExtractResult =
  | { kind: "text"; text: string }
  | { kind: "file"; url: string; name: string; mime: string; size: number };

export default function ExtractPanel() {
  const [imagePreview, setImagePreview] = useState<string | null>(null);
  const [imageName, setImageName] = useState("");
  const [dimensions, setDimensions] = useState<{ width: number; height: number } | null>(null);
  const [stage, setStage] = useState<Stage>("idle");
  const [lockedBody, setLockedBody] = useState<Uint8Array | null>(null);
  const [password, setPassword] = useState("");
  const [showPassword, setShowPassword] = useState(false);
  const [unlocking, setUnlocking] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<ExtractResult | null>(null);
  const [encrypted, setEncrypted] = useState(false);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    return () => {
      if (imagePreview) URL.revokeObjectURL(imagePreview);
    };
  }, [imagePreview]);

  useEffect(() => {
    return () => {
      if (result?.kind === "file") URL.revokeObjectURL(result.url);
    };
  }, [result]);

  const presentPayload = useCallback((payload: SecretPayload) => {
    if (payload.type === "text") {
      setResult({ kind: "text", text: payload.text ?? "" });
    } else {
      const bytes = payload.fileBytes ?? new Uint8Array(0);
      const blob = new Blob([bytes], { type: payload.mimeType || "application/octet-stream" });
      setResult({
        kind: "file",
        url: URL.createObjectURL(blob),
        name: payload.fileName || "secret.bin",
        mime: payload.mimeType || "application/octet-stream",
        size: bytes.length,
      });
    }
    setStage("done");
  }, []);

  const handleImage = useCallback(
    async (file: File) => {
      setStage("reading");
      setError(null);
      setResult(null);
      setLockedBody(null);
      setPassword("");
      setEncrypted(false);
      setCopied(false);

      if (!file.type.startsWith("image/")) {
        setError("Please choose an image file generated by PryKrypt.");
        setStage("error");
        return;
      }

      try {
        const previewUrl = URL.createObjectURL(file);
        const data = await readImageData(file);

        setImagePreview(previewUrl);
        setImageName(file.name);
        setDimensions({ width: data.width, height: data.height });

        const { header, body } = extractContainer(data);
        setEncrypted(header.encrypted);

        if (header.encrypted) {
          setLockedBody(body);
          setStage("locked");
          return;
        }

        presentPayload(deserializePayload(body));
      } catch (cause) {
        setError(toMessage(cause, "Could not read hidden data from this image."));
        setStage("error");
      }
    },
    [presentPayload],
  );

  const handleUnlock = async (event: React.FormEvent) => {
    event.preventDefault();
    if (!lockedBody) return;

    setUnlocking(true);
    setError(null);

    try {
      if (!password) {
        throw new PryKryptError("PASSWORD_REQUIRED", "Enter the password used when hiding this secret.");
      }
      const plain = await decryptBytes(lockedBody, password);
      presentPayload(deserializePayload(plain));
    } catch (cause) {
      setError(toMessage(cause, "Could not decrypt the payload."));
      setStage("locked");
    } finally {
      setUnlocking(false);
    }
  };

  const handleReset = () => {
    setImagePreview(null);
    setImageName("");
    setDimensions(null);
    setStage("idle");
    setLockedBody(null);
    setPassword("");
    setResult(null);
    setError(null);
    setEncrypted(false);
    setCopied(false);
  };

  const handleCopy = async (text: string) => {
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1600);
    } catch {
      /* clipboard may be unavailable */
    }
  };

  return (
    <div className="space-y-5 sm:space-y-6">
      <Reveal>
        <header>
          <h1 className="text-2xl font-black tracking-tight text-white sm:text-3xl">
            Extract a Secret
          </h1>
          <p className="mt-2 max-w-2xl text-sm leading-relaxed text-slate-400">
            Load a PryKrypt-generated PNG. The payload is read from the image&apos;s pixel data
            locally — nothing leaves your device.
          </p>
        </header>
      </Reveal>

      <Reveal>
        <section className="card p-4 sm:p-6">
          <StepHeader
            index={1}
            title="PryKrypt image"
            subtitle="Must be the original PNG — resized or JPEG versions will not work."
          />

          <div className="mt-4">
            {imagePreview ? (
              <div className="flex flex-col gap-4 sm:flex-row sm:items-center">
                <div className="relative overflow-hidden rounded-xl border border-white/10 bg-ink-900">
                  {/* eslint-disable-next-line @next/next/no-img-element */}
                  <img
                    src={imagePreview}
                    alt="Loaded image"
                    className="h-40 w-full object-contain sm:h-40 sm:w-48"
                  />
                  <button
                    type="button"
                    aria-label="Remove image"
                    onClick={handleReset}
                    className="absolute right-2 top-2 flex h-7 w-7 items-center justify-center rounded-full bg-black/60 text-slate-200 backdrop-blur transition hover:bg-black/80"
                  >
                    <X size={14} />
                  </button>
                </div>
                <div className="min-w-0 flex-1 text-sm">
                  <p className="truncate font-semibold text-slate-100">{imageName}</p>
                  {dimensions ? (
                    <p className="mt-1 text-slate-400">
                      {dimensions.width} × {dimensions.height} px
                    </p>
                  ) : null}
                  <button
                    type="button"
                    className="btn-ghost mt-3 w-full sm:w-auto"
                    onClick={handleReset}
                  >
                    <RefreshCw size={14} />
                    Load a different image
                  </button>
                </div>
              </div>
            ) : (
              <ImageDropzone
                onFile={handleImage}
                title="Drop a PryKrypt PNG here"
                hint="or tap to browse · decoding runs entirely in your browser"
              />
            )}
          </div>

          {stage === "reading" ? (
            <p className="mt-4 flex items-center gap-2 text-sm text-pry-300">
              <span className="h-4 w-4 animate-spin rounded-full border-2 border-pry-400/40 border-t-pry-300" />
              Scanning pixel data…
            </p>
          ) : null}

          {stage === "error" && error ? (
            <div className="mt-4">
              <Alert tone="error" title="Extraction failed">
                {error}
              </Alert>
            </div>
          ) : null}
        </section>
      </Reveal>

      {stage === "locked" ? (
        <section className="card animate-fade-up p-4 sm:p-6">
          <StepHeader
            index={2}
            title="Password required"
            subtitle="This payload is protected with AES-256-GCM."
          />

          <form onSubmit={handleUnlock} className="mt-4 space-y-4">
            <div>
              <label className="label" htmlFor="extract-password">
                Password
              </label>
              <div className="relative">
                <KeyRound
                  size={15}
                  className="pointer-events-none absolute left-3 top-1/2 -translate-y-1/2 text-slate-500"
                />
                <input
                  id="extract-password"
                  type={showPassword ? "text" : "password"}
                  className="field pl-9 pr-20"
                  placeholder="Enter the password"
                  value={password}
                  onChange={(event) => setPassword(event.target.value)}
                  autoComplete="off"
                  disabled={unlocking}
                />
                <button
                  type="button"
                  onClick={() => setShowPassword((value) => !value)}
                  className="absolute right-2 top-1/2 -translate-y-1/2 rounded-lg px-2.5 py-1 text-xs font-semibold text-slate-400 hover:text-slate-200"
                >
                  {showPassword ? "Hide" : "Show"}
                </button>
              </div>
            </div>

            {error ? (
              <Alert tone="error" title="Incorrect password">
                {error}
              </Alert>
            ) : null}

            <button type="submit" className="btn-primary w-full sm:w-auto" disabled={unlocking}>
              {unlocking ? (
                <>
                  <span className="h-4 w-4 animate-spin rounded-full border-2 border-white/40 border-t-white" />
                  Decrypting…
                </>
              ) : (
                <>
                  <Unlock size={16} />
                  Unlock &amp; extract
                </>
              )}
            </button>
          </form>
        </section>
      ) : null}

      {stage === "done" && result ? (
        <section className="card animate-fade-up p-4 sm:p-6">
          <StepHeader
            index={2}
            title="Extracted secret"
            subtitle={
              encrypted
                ? "Decrypted locally with AES-256-GCM."
                : "This payload was not encrypted."
            }
          />

          {result.kind === "text" ? (
            <div className="mt-4 space-y-4">
              <Alert tone="success" title="Message recovered">
                The hidden text was read successfully.
              </Alert>
              <div className="rounded-xl border border-white/10 bg-ink-900/80 p-3 sm:p-4">
                <pre className="mono max-h-72 overflow-auto whitespace-pre-wrap break-words text-[13px] leading-relaxed text-slate-200 sm:text-sm">
                  {result.text || "(empty message)"}
                </pre>
              </div>
              <button
                type="button"
                className="btn-ghost w-full sm:w-auto"
                onClick={() => handleCopy(result.text)}
              >
                <Copy size={14} />
                {copied ? "Copied!" : "Copy to clipboard"}
              </button>
            </div>
          ) : (
            <div className="mt-4 space-y-4">
              <div className="flex items-center gap-3 rounded-xl border border-emerald-500/30 bg-emerald-500/10 px-4 py-3 text-sm text-emerald-200">
                <FileText size={18} className="shrink-0" />
                <div className="min-w-0">
                  <p className="truncate font-semibold">{result.name}</p>
                  <p className="text-xs text-emerald-200/80">{formatBytes(result.size)}</p>
                </div>
              </div>
              <a
                className="btn-primary w-full sm:w-auto"
                href={result.url}
                download={result.name}
              >
                <Download size={16} />
                Download {result.name}
              </a>
            </div>
          )}
        </section>
      ) : null}

      {stage === "locked" ? (
        <p className="flex items-center justify-center gap-1.5 text-xs text-slate-500">
          <Lock size={12} /> Decryption happens on this device
        </p>
      ) : null}
    </div>
  );
}